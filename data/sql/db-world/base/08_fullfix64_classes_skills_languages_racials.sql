-- FULLFIX 6.4 - deterministic repair for custom races 13-16
-- This update is intentionally a NEW filename so AzerothCore applies it to existing FULLFIX 6.3 installs.
-- It restores the explicit class spell/proficiency packages shipped by the source mods,
-- then enforces the requested language and racial sets.
-- No C++ rebuild is required for this update.

SET @HE := 4096;   -- race 13 High Elf
SET @MH := 8192;   -- race 14 Mag'har Orc
SET @OG := 16384;  -- race 15 Ogre
SET @DI := 32768;  -- race 16 Dark Iron Dwarf
SET @CUSTOM := @HE | @MH | @OG | @DI;

-- ---------------------------------------------------------------------------
-- 1) SkillLine ownership: weapons, armor and languages inherit from parent races.
--    High Elf <- Blood Elf, Mag'har/Ogre <- Orc, Dark Iron <- Dwarf.
-- ---------------------------------------------------------------------------
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @HE WHERE (`raceMask` & 512) <> 0;
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @MH | @OG WHERE (`raceMask` & 2) <> 0;
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @DI WHERE (`raceMask` & 4) <> 0;

-- Explicit language skill safety net.
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @HE WHERE `skill` IN (98,137);
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @MH | @OG WHERE `skill`=109;
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` | @DI WHERE `skill` IN (98,111);

-- Remove obsolete synthetic racial SkillLines from older revisions.
DELETE FROM `playercreateinfo_skills` WHERE `skill`=794;
UPDATE `playercreateinfo_skills` SET `raceMask`=`raceMask` & ~@OG WHERE `skill`=793 AND (`raceMask` & @OG)<>0;
DELETE FROM `playercreateinfo_skills` WHERE `raceMask`=0;

-- ---------------------------------------------------------------------------
-- 2) Rebuild class starter/class proficiency spells for High Elf, Mag'har and Ogre.
--    FULLFIX6.3 deleted these rows and attempted to reconstruct them only from donors.
--    Replaying the original explicit race packages makes the result independent of the
--    exact ACDB donor-row layout.
-- ---------------------------------------------------------------------------
DELETE FROM `playercreateinfo_spell_custom` WHERE (`racemask` & (@HE|@MH|@OG)) <> 0;

